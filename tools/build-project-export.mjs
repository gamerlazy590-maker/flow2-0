// Regenerates server/src/projectExport.generated.ts — the embedded copy of
// this project's own source files that powers the in-app "Download the full
// project (.zip)" export in the Publishing & deployment section.
//
// Run directly:  bun run export:manifest
// It also runs automatically as the first step of `bun run build`, so the
// downloadable ZIP always matches the code that was built.
//
// The generated module deliberately does not embed itself; the export
// action reconstructs its source from the same data when assembling the
// ZIP, so the downloaded project is complete with no missing files.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

// Every source file that makes up the deployable project, in ZIP order.
// Build outputs (client/dist, server/dist), node_modules, and the live
// app's database/user media are intentionally excluded — see README.md.
const PROJECT_FILES = [
  "README.md",
  "DEPLOY.md",
  "package.json",
  "bun.lock",
  "bunfig.toml",
  "tsconfig.base.json",
  "vercel.json",
  "space.json",
  "robots.txt",
  "sitemap.xml",
  ".gitignore",
  "client/index.html",
  "client/build.mjs",
  "client/tsconfig.json",
  "client/src/App.tsx",
  "client/src/Logo.tsx",
  "client/src/api.ts",
  "client/src/main.tsx",
  "client/src/theme.css",
  "client/src/globals.d.ts",
  "client/src/assets/showcase-3drender.webp",
  "client/src/assets/showcase-anime.webp",
  "client/src/assets/showcase-cyberpunk.webp",
  "client/src/assets/showcase-landscape.webp",
  "client/src/assets/showcase-nebula.webp",
  "client/src/assets/showcase-portrait.webp",
  "server/src/actions.ts",
  "server/src/schema.ts",
  "server/src/privileged.ts",
  "server/tsconfig.json",
  "drizzle/0001_initial.sql",
  "drizzle/0002_users_sessions_creations.sql",
  "drizzle/0003_creation_video_file_columns.sql",
  "drizzle/meta/_journal.json",
  "tools/build-project-export.mjs",
];

const entries = PROJECT_FILES.map((rel) => {
  const abs = join(root, rel);
  if (!existsSync(abs)) {
    throw new Error(`Project export is missing a required file: ${rel}`);
  }
  return { path: rel, base64: readFileSync(abs).toString("base64") };
});

const lines = [
  "// @generated by tools/build-project-export.mjs — do not edit by hand.",
  "export const PROJECT_EXPORT_FILES: ReadonlyArray<{ path: string; base64: string }> = [",
  ...entries.map((entry) => `  ${JSON.stringify(entry)},`),
  "];",
  "",
];

const outPath = join(root, "server/src/projectExport.generated.ts");
writeFileSync(outPath, lines.join("\n"));
console.log(
  `projectExport.generated.ts: embedded ${entries.length} files (${entries.reduce(
    (sum, e) => sum + Math.floor((e.base64.length * 3) / 4),
    0,
  )} bytes of source).`,
);
